#!/usr/bin/env python3
"""ps5/tsword/configure.py - writes build/tsword/build.ninja: TotK Recomp's runtime (tsword/runtime, synced by
tools/sync-tsword.sh) compiled for the console with the payload SDK's prospero-clang into one static archive,
libtsword.a, that the title links.

    ps5/tsword/configure.py --sdk <payload SDK> --deps <prefix> [--out build/tsword]

--deps: the console builds of what the runtime uses (ps5/tsword/deps.sh): include/ with SDL3 (headers; the title
implements the subset), vulkan, vk_mem_alloc.h, opus, vpx, zstd.

The sources are tools/build_game.py's runtime_sources() for Linux - every runtime/*.c, *.cpp, ui/*.cpp and Dear ImGui -
with platform/ps5.c in place of platform/linux.c, less the install side (INSTALL_SIDE: romfs.c, patches.c, ov_zstd.c,
mouse_direct.c), which the PC builds with the game code for its version and so the PS5 export does too. The flags are
build_game.py's RT_FLAGS with the console's CPU (Zen 2, x86-64-v3 and more), and the console's layout.h
(ps5/tsword/include: what every game version shares).
"""
import argparse
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
T = os.path.join(ROOT, "tsword")
R = os.path.join(T, "runtime")
INSTALL_SIDE = {"romfs.c", "patches.c", "ov_zstd.c", "mouse_direct.c"}


def sources():
    out = []
    for d, exts in (("", (".c", ".cpp")), ("platform", (".c",)), ("ui", (".cpp",)), ("third_party/imgui", (".cpp",)),
                    ("third_party/imgui/backends", (".cpp",))):
        for f in sorted(os.listdir(os.path.join(R, d))):
            stem, ext = os.path.splitext(f)
            if ext not in exts or f in INSTALL_SIDE:
                continue
            if stem.endswith("_win") or f in ("win32.c", "linux.c"):
                continue
            out.append(os.path.join(d, f) if d else f)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdk", required=True)
    ap.add_argument("--deps", required=True)
    ap.add_argument("--out", default=os.path.join(ROOT, "build", "tsword"))
    a = ap.parse_args()
    sdk, deps, out = (os.path.abspath(x) for x in (a.sdk, a.deps, a.out))
    os.makedirs(out, exist_ok=True)
    if not os.path.exists(os.path.join(R, "platform", "ps5.c")):
        sys.exit("tsword/ has no runtime/platform/ps5.c: run tools/sync-tsword.sh")
    version = open(os.path.join(T, "VERSION")).read().strip() if os.path.exists(os.path.join(T, "VERSION")) else "?"
    commit = next((l.split(": ", 1)[1].strip() for l in open(os.path.join(T, "SOURCE")) if l.startswith("commit: ")), "?")

    cc = os.path.join(sdk, "bin", "prospero-clang")
    cxx = os.path.join(sdk, "bin", "prospero-clang++")
    ar = os.path.join(sdk, "bin", "prospero-ar")
    inc = (f"-I{ROOT}/ps5/tsword/include -I{R} -I{R}/ui -I{R}/third_party/imgui -I{R}/third_party/imgui/backends "
           f"-I{out}/inc -I{deps}/include")
    # (build_game.py's RT_FLAGS: -O2 -g -Wall -fno-strict-aliasing, the CPU level; frame pointers kept for crash logs)
    common = (f"-O2 -g -march=znver2 -DRT_CPU_LEVEL=3 -fno-omit-frame-pointer -fno-strict-aliasing -Wall "
              f"-Wno-unknown-warning-option -Wno-unused-function -DTSWORD_PS5=1 {inc}")
    cflags = f"-std=gnu17 {common}"
    cxxflags = f"-std=c++17 {common}"

    n = [f"# generated by ps5/tsword/configure.py (TotK Recomp {version}, {commit[:12]}): do not edit\n",
         f"builddir = {out}\n",
         f"rule cc\n  command = {cc} -MD -MF $out.d $flags -c $in -o $out\n  depfile = $out.d\n  deps = gcc\n  description = cc $in\n",
         f"rule cxx\n  command = {cxx} -MD -MF $out.d $flags -c $in -o $out\n  depfile = $out.d\n  deps = gcc\n  description = c++ $in\n",
         f"rule ar\n  command = rm -f $out && {ar} rcs $out $in\n  description = ar $out\n",
         # the menu's font as C bytes: the console's clang has no #embed (ps5/tsword-patches/0001)
         f"rule bytes\n  command = {sys.executable} -c \"import sys; d=open(sys.argv[1],'rb').read(); "
         f"open(sys.argv[2],'w').write(','.join(str(b) for b in d))\" $in $out\n  description = bytes $out\n",
         f"rule configure\n  command = {sys.executable} {os.path.abspath(__file__)} --sdk {sdk} --deps {deps} --out {out}\n  generator = 1\n",
         f"build {out}/build.ninja: configure {os.path.abspath(__file__)} {T}/SOURCE\n"]
    font = f"{out}/inc/roboto_ttf.inc"
    n.append(f"build {font}: bytes {R}/ui/fonts/Roboto-Medium.ttf\n")
    objs = []
    for s in sources():
        o = f"{out}/obj/{os.path.splitext(s)[0]}.o"
        objs.append(o)
        cpp = s.endswith(".cpp")
        extra = f" | {font}" if s == "ui/menu.cpp" else ""
        n.append(f"build {o}: {'cxx' if cpp else 'cc'} {R}/{s}{extra}\n  flags = {cxxflags if cpp else cflags}\n")
    n.append(f"build {out}/libtsword.a: ar {' '.join(objs)}\n")
    n.append(f"default {out}/libtsword.a\n")
    with open(os.path.join(out, "build.ninja"), "w") as f:
        f.write("\n".join(n))
    print(f"configure: {len(objs)} objects -> {out}/libtsword.a (TotK Recomp {version}, {commit[:12]})")
    return 0


sys.exit(main())
