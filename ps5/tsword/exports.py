#!/usr/bin/env python3
"""ps5/tsword/exports.py --sdk <payload SDK> --out <exports.c> [--names <exports.txt>] [--need <need.txt>]
                       [--lib <archive>]... <object>... - what the game code
(tsgame.so, TSword Setup's PS5 export) may import on the console, by name: gamecode.c's loader (elfload.c) resolves
the library's imports from this table, a title having no dynamic linker that would find them (as WSword PS5's).
  - every C function and variable the runtime's objects define (rt_dispatch, rt_svc, rt_register_host, cfg_*, rt_log...)
  - the public functions of the libraries given with --lib that the install side calls (zstd: ZSTD_*)
  - the functions the game code's libc headers declare (HEADERS: string.h, math.h... as WSword PS5's table, what the
    lifted C includes) and what CI's dry run of such a library imports (--need: tools/build_ps5.py --dry-run, the
    install side - romfs.c, patches.c, ov_zstd.c, mouse_direct.c - and every inline function of cpu.h and simd.h),
    those a module a title loads exports; nothing more, as each is an import of the title the console resolves
  - EXTRA: what the compiler itself may call in code that names none of them (copies, clears; the thread-local
    variables of the install side, built with -femulated-tls as the title is)
The table is sorted by name; each entry is the symbol's address as the title's own link resolves it (a name the title
wraps - fopen, getcwd... ps5_cwd.c - is its wrapper).
"""
import argparse
import glob
import os
import re
import subprocess

HEADERS = ["string.h", "strings.h", "math.h", "fenv.h", "setjmp.h"]
EXTRA = ["memcpy", "memmove", "memset", "memcmp"]
# stubs of modules a title doesn't load: their names are null at run time (ps5/tools/link-title.sh refuses them)
NOT_LOADED = ("libkernel_sys.so", "libScePosixForWebKit.so")
LIB_PREFIXES = ("ZSTD_",)


def nm(tool, args):
    return subprocess.run([tool] + args, capture_output=True, text=True).stdout


def defined(tool, files, kinds="TDBRCVW"):
    names = set()
    for line in nm(tool, ["--defined-only", "-g"] + files).splitlines():
        p = line.split()
        if len(p) == 3 and p[1] in kinds:
            names.add(p[2])
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdk", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--lib", action="append", default=[])
    ap.add_argument("--need")
    ap.add_argument("--names")
    ap.add_argument("objects", nargs="+")
    a = ap.parse_args()
    tool = os.path.join(a.sdk, "bin", "llvm-nm")
    # the runtime's (not C++'s, nor the compiler's own helpers): the loader stubs' slots (tsg_p_*) and the copies of
    # the library's data stay in, harmlessly; the library binds its own names first (-Bsymbolic)
    names = {n for n in defined(tool, a.objects) if not n.startswith(("_Z", "__", "."))}
    lib = {n for n in defined(tool, a.lib, "T") if n.startswith(LIB_PREFIXES)} if a.lib else set()
    exported = set()
    for so in glob.glob(os.path.join(a.sdk, "target", "lib", "*.so")):
        if os.path.basename(so) in NOT_LOADED:
            continue
        exported.update(l.split()[-1] for l in nm(tool, ["-D", "--defined-only", so]).splitlines() if l.split())
    declared = set()
    inc = os.path.join(a.sdk, "target", "include")
    for h in HEADERS:
        path = os.path.join(inc, h)
        if not os.path.isfile(path):
            continue
        text = re.sub(r"/\*.*?\*/", " ", open(path, errors="replace").read(), flags=re.S)
        for m in re.finditer(r"\b([A-Za-z_]\w*)\s*\(", text):
            declared.add(m.group(1))
    declared = {n for n in declared if not n.startswith("__") or n in ("__isnan", "__isinf")}
    need = set(open(a.need).read().split()) if a.need else set()
    libc = (declared | need) & exported
    # what the dry run imports that neither the runtime, the libraries nor libc defines: the compiler's helpers the
    # title links (__emutls_get_address...), taken if the title has them - its link says so if it hasn't
    helpers = need - names - lib - exported - {n for n in need if n.startswith(("tsg_", "rt_layout"))}
    allnames = sorted(names | lib | libc | set(EXTRA) | helpers)
    out = ["// generated by ps5/tsword/exports.py: do not edit", "#include <stddef.h>",
           "typedef struct { const char *name; void *addr; } ElfExport;"]
    for i, n in enumerate(allnames):
        out.append(f'extern char x{i}[] __asm__("{n}");')
    out.append("const ElfExport g_tsword_exports[] = {")
    out.extend(f'    {{"{n}", x{i}}},' for i, n in enumerate(allnames))
    out.append("};")
    out.append(f"const size_t g_tsword_nexports = {len(allnames)};")
    with open(a.out, "w") as f:
        f.write("\n".join(out) + "\n")
    if a.names:
        with open(a.names, "w") as f:
            f.write("\n".join(allnames) + "\n")
    lacking = sorted(need - set(allnames))
    if lacking:
        print(f"exports: the dry run's library imports what nothing here has: {' '.join(lacking)}")
    print(f"exports: {len(names)} of the runtime's, {len(lib)} of the libraries', {len(libc)} of libc's, "
          f"{len(helpers)} of the compiler's ({' '.join(sorted(helpers))})")


main()
