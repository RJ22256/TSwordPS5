#!/usr/bin/env python3
"""ps5/ut/configure.py - writes build/ut/build.ninja: UltraTears' runtime (ultratears/, synced by
tools/sync-ultratears.sh) compiled for the console with the payload SDK's prospero-clang into one static archive,
libut.a, that the title links.

    ps5/ut/configure.py --sdk <payload SDK> --deps <prefix> [--out build/ut]

--deps: the console builds of what the runtime uses (ps5/ut/deps.sh): include/ with SDL3 (headers; the title
implements the subset), vulkan, opus, vpx, zstd.

The sources are tools/build_game.py's for Linux - LINUX_RUNTIME, TARGETS['ultratears'] and GFX - with
src/runtime/platform/ps5.c in place of linux.c; the flags are its CFLAGS with the console's CPU (Zen 2) and frame
pointers kept for the crash logs. Every thread the runtime starts goes through ut_pthread_create (ps5.c: its stack in
direct memory), and the title's own side (ps5/ut: the SDL3 subset, the game code loader, the process end, the working
directory) is added, with the table of what the game code may import (exports.py).
"""
import argparse
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
U = os.path.join(ROOT, "ultratears")
P = os.path.join(ROOT, "ps5", "ut")


def sources():
    text = open(os.path.join(U, "tools", "build_game.py")).read()
    ns = {}
    exec(text[text.index("RUNTIME = "):text.index("GFX_INCLUDES")], ns)
    i = text.index("LINUX_RUNTIME = ")
    exec(text[i:text.index("]", i) + 1], ns)
    runtime = [s.replace("platform/linux.c", "platform/ps5.c") for s in ns["LINUX_RUNTIME"]]
    return runtime + ns["TARGETS"]["ultratears"] + ns["GFX"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdk", required=True)
    ap.add_argument("--deps", required=True)
    ap.add_argument("--out", default=os.path.join(ROOT, "build", "ut"))
    ap.add_argument("--need", help="build_ps5.py --dry-run's need.txt: what the game code imports beyond the runtime")
    a = ap.parse_args()
    sdk, deps, out = (os.path.abspath(x) for x in (a.sdk, a.deps, a.out))
    os.makedirs(os.path.join(out, "inc"), exist_ok=True)
    if not os.path.exists(os.path.join(U, "src", "runtime", "platform", "ps5.c")):
        sys.exit("ultratears/ has no src/runtime/platform/ps5.c: run tools/sync-ultratears.sh")
    commit = next((l.split(": ", 1)[1].strip() for l in open(os.path.join(U, "SOURCE")) if l.startswith("commit: ")), "?")
    sys.path.insert(0, os.path.join(U, "tools"))
    import build_ps5   # (ps5/ut-overlay/tools/build_ps5.py: the PS5 export; its game code id)
    gid = build_ps5.gamecode_id(U)
    # the version header and the window icon tools/build_game.py writes (version_files)
    with open(os.path.join(out, "inc", "version.h"), "w") as f:
        f.write(f'#define ULTRS_VERSION "{build_ps5.ut_version(U)} (TSword PS5)"\n#define ULTRS_COMMIT "{commit[:7]}"\n')
    with open(os.path.join(out, "inc", "icon_png.h"), "w") as f:
        f.write("static const unsigned char ultrs_icon_png[] = {0};\nstatic const unsigned int ultrs_icon_png_len = 1;\n")

    cc = os.path.join(sdk, "bin", "prospero-clang")
    cxx = os.path.join(sdk, "bin", "prospero-clang++")
    ar = os.path.join(sdk, "bin", "prospero-ar")
    base = (f"-O2 -g -march=znver2 -fno-omit-frame-pointer -fno-strict-aliasing -D_FILE_OFFSET_BITS=64 "
            f"-I{out}/inc -I{U}/src/runtime -I{deps}/include")
    rt = f"{base} -Wall -Wno-unused-function -Wno-unknown-warning-option -Dpthread_create=ut_pthread_create"
    gfx = f"{base} -w -I{U}/src/gfx -I{U}/src/gfx/nvn -I{U}/src/gfx/nvn/include -I{U}/src/gfx/compat " \
          f"-Dpthread_create=ut_pthread_create"
    # (from ultratears/: text_entry.c's .incbin names assets/ from there, as build_game.py runs)
    n = [f"# generated by ps5/ut/configure.py (UltraTears {commit[:12]}): do not edit\n",
         f"builddir = {out}\n",
         f"rule cc\n  command = cd {U} && {cc} -MD -MF $out.d $flags -c $in -o $out\n  depfile = $out.d\n  deps = gcc\n  description = cc $in\n",
         f"rule cxx\n  command = cd {U} && {cxx} -MD -MF $out.d $flags -c $in -o $out\n  depfile = $out.d\n  deps = gcc\n  description = c++ $in\n",
         f"rule ar\n  command = rm -f $out && {ar} rcs $out $in\n  description = ar $out\n"]
    objs = []
    for s in sources():
        o = f"{out}/obj/{os.path.splitext(s)[0]}.o"
        objs.append(o)
        if s.endswith(".cpp"):
            n.append(f"build {o}: cxx {U}/{s}\n  flags = {gfx} -std=c++17 -fno-exceptions -fno-rtti\n")
        else:
            flags = gfx if s.startswith("src/gfx/") else rt
            if s.endswith("platform/ps5.c"):
                flags = flags.replace(" -Dpthread_create=ut_pthread_create", "")   # (it defines it: the real one)
            n.append(f"build {o}: cc {U}/{s}\n  flags = {flags}\n")
    # the console's side (ps5/ut): the SDL3 subset, the game code loader, the process end and working directory,
    # clang's CPU model, the Vulkan commands for the SDL subset (vkgen.py)
    side_flags = f"-std=gnu17 -O2 -g -march=znver2 -fno-omit-frame-pointer -Wall -I{deps}/include"
    side = {"sdl/sdl_ps5.c": side_flags, "sdl_extra.c": side_flags, "ps5_glue.c": side_flags, "ps5_cwd.c": side_flags,
            "cpu_model.c": side_flags, "elfload.c": side_flags,
            "gamecode.c": f"{side_flags} -DTSWORD_GAMECODE_ID='\"{gid}\"'"}
    for s_, fl in side.items():
        o = f"{out}/obj/ps5/{os.path.splitext(s_)[0]}.o"
        objs.append(o)
        n.append(f"build {o}: cc {P}/{s_}\n  flags = {fl}\n")
    # (TSword PS5) the console menu and the performance overlay (ps5/ut/ui, Dear ImGui in ps5/third_party/imgui): C++,
    # drawn by the present thread (src/vk/present.c tsword_ui_record). Not in the game code's import table (exports.py):
    # the game code calls none of it.
    im = os.path.join(ROOT, "ps5", "third_party", "imgui")
    ui_flags = (f"-std=c++17 -O2 -g -march=znver2 -fno-omit-frame-pointer -fno-exceptions -fno-rtti -Wall "
                f"-Wno-unknown-warning-option -I{deps}/include -I{im} -I{im}/backends -I{U}/src/vk -I{P}/ui "
                f"-DIMGUI_IMPL_VULKAN_NO_PROTOTYPES -DIMGUI_DISABLE_DEFAULT_SHELL_FUNCTIONS")
    ui_objs = []
    for src in [f"{P}/ui/tsword_ui.cpp", f"{P}/ui/option_rows.cpp", f"{im}/imgui.cpp", f"{im}/imgui_draw.cpp",
                f"{im}/imgui_tables.cpp", f"{im}/imgui_widgets.cpp", f"{im}/backends/imgui_impl_vulkan.cpp"]:
        o = f"{out}/obj/ps5/ui/{os.path.splitext(os.path.basename(src))[0]}.o"
        ui_objs.append(o)
        fl = ui_flags if "/ps5/ut/" in src else ui_flags.replace(" -Wall", " -w")
        n.append(f"build {o}: cxx {src}\n  flags = {fl}\n")
    # frame generation (ps5/ut/ui/framegen.c, lsfg.cpp; ps5/third_party/lsfg-vk, GPL-3.0: its README.TSword.md), with
    # C++ exceptions as lsfg-vk is written; lsfg_prefix.h first (FreeBSD's major() / minor() macros)
    lsfg = os.path.join(ROOT, "ps5", "third_party", "lsfg-vk")
    lsfg_common = (f"-O2 -g -march=znver2 -fno-omit-frame-pointer -std=c++20 -fexceptions -frtti -include {P}/ui/lsfg_prefix.h "
                   f"-I{deps}/include -I{lsfg}/lsfg-vk-common/include -I{lsfg}/lsfg-vk-backend/include")
    o = f"{out}/obj/ps5/ui/framegen.o"
    ui_objs.append(o)
    n.append(f"build {o}: cc {P}/ui/framegen.c\n  flags = -std=gnu17 -O2 -g -march=znver2 -fno-omit-frame-pointer -Wall "
             f"-I{deps}/include -I{U}/src/vk -I{P}/ui\n")
    o = f"{out}/obj/ps5/ui/lsfg.o"
    ui_objs.append(o)
    n.append(f"build {o}: cxx {P}/ui/lsfg.cpp\n  flags = {lsfg_common} -Wall\n")
    for d in ("lsfg-vk-common/src", "lsfg-vk-backend/src"):
        for dp, _, fs in sorted(os.walk(os.path.join(lsfg, d))):
            for f in sorted(fs):
                if f.endswith(".cpp"):
                    src = os.path.join(dp, f)
                    o = f"{out}/obj/ps5/lsfg/{os.path.relpath(src, lsfg)[:-4]}.o"
                    ui_objs.append(o)
                    n.append(f"build {o}: cxx {src}\n  flags = {lsfg_common} -DVK_NO_PROTOTYPES -I{lsfg}/lsfg-vk-backend/src -w\n")
    vkc = f"{out}/gen/vk_dispatch.c"
    n.append(f"rule vkgen\n  command = {sys.executable} {P}/vkgen.py $in $out\n  description = vkgen\n")
    n.append(f"build {vkc}: vkgen {deps}/include/vulkan/vulkan_core.h | {P}/vkgen.py\n")
    objs.append(f"{out}/obj/ps5/vk_dispatch.o")
    n.append(f"build {out}/obj/ps5/vk_dispatch.o: cc {vkc}\n  flags = -std=gnu17 -O2 -g -march=znver2 -w -I{deps}/include\n")
    # what the game code may import, by name (exports.py: gamecode.c's loader resolves the library's imports with it)
    need = f" --need {os.path.abspath(a.need)}" if a.need else ""
    n.append(f"rule exports\n  command = {sys.executable} {P}/exports.py --sdk {sdk} --out {out}/gen/exports.c "
             f"--names {out}/exports.txt{need} $in\n  description = exports\n")
    n.append(f"build {out}/gen/exports.c | {out}/exports.txt: exports {' '.join(objs)} | {P}/exports.py\n")
    n.append(f"build {out}/obj/ps5/exports.o: cc {out}/gen/exports.c\n  flags = -std=gnu17 -O2 -w\n")
    objs.append(f"{out}/obj/ps5/exports.o")
    n.append(f"build {out}/libut.a: ar {' '.join(objs + ui_objs)}\n")
    n.append(f"default {out}/libut.a\n")
    with open(os.path.join(out, "build.ninja"), "w") as f:
        f.write("\n".join(n))
    with open(os.path.join(out, "gamecode.id"), "w") as f:
        f.write(gid + "\n")
    print(f"configure: {len(objs) + len(ui_objs)} objects -> {out}/libut.a (UltraTears {commit[:12]}), game code id {gid}")
    return 0


sys.exit(main())
